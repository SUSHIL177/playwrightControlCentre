import fs from 'fs';
import path from 'path';
import type { BrowserType } from '../../shared/types';

export interface EffectiveConfig {
  /** Absolute path of the generated wrapper config (pass to `playwright test --config=…`). */
  configPath: string;
  /** Removes the wrapper. Safe to call multiple times. */
  cleanup: () => void;
}

const WRAPPER_NAME = '.pacc.effective.config.ts';

/**
 * Builds a transient Playwright config that *overrides* whatever the imported project's
 * config declares for browsers: the user's selection wins, full stop.
 *
 * The wrapper re-exports the base config with its `projects` replaced by one project per
 * selected browser. Playwright transpiles the config it is given (esbuild), so importing
 * the project's own TS config from the wrapper works — including configs that themselves
 * import helper modules (resolution stays relative to the base file's real location).
 *
 * The wrapper lives in the base config's own directory because (a) node module
 * resolution for `@playwright/test` must walk up to the project's node_modules, and
 * (b) the base config may resolve relative paths (testDir, e2e dirs) against its own
 * folder. It is deleted in the run's `close`/`error` handlers and defensively on spawn
 * failure, so the user's repo is never left with stray files.
 *
 * Returns null when there is no base config — in that case we still want the override, so
 * a standalone effective config is generated in the project root instead.
 */
export function writeEffectiveConfig(
  projectRoot: string,
  baseConfigPath: string | null | undefined,
  browsers: BrowserType[]
): EffectiveConfig | null {
  const uniqueBrowsers = Array.from(new Set(browsers.filter(Boolean)));
  if (uniqueBrowsers.length === 0) return null;

  const baseDir = baseConfigPath && fs.existsSync(baseConfigPath) ? path.dirname(path.resolve(baseConfigPath)) : path.resolve(projectRoot);
  const configPath = path.join(baseDir, WRAPPER_NAME);
  const importTarget = baseConfigPath && fs.existsSync(baseConfigPath)
    ? baseConfigPath.replace(/\\/g, '/').replace(/\.(ts|mts|cts|js|mjs|cjs)$/i, '')
    : null;

  const projectsLiteral = uniqueBrowsers
    .map((b) => `  { name: ${JSON.stringify(b)}, use: { browserName: ${JSON.stringify(b)} } }`)
    .join(',\n');

  const contents = importTarget
    ? `// Generated by Playwright Control Center for a single run — DO NOT EDIT, deleted after the run.
import baseConfigModule from ${JSON.stringify(importTarget)};
import { defineConfig } from '@playwright/test';

const base: any = (baseConfigModule as any)?.default ?? baseConfigModule ?? {};

export default defineConfig({
  ...(typeof base === 'object' && base ? base : {}),
  projects: [
${projectsLiteral}
  ],
});
`
    : `// Generated by Playwright Control Center — DO NOT EDIT, deleted after the run.
import { defineConfig } from '@playwright/test';

export default defineConfig({
  testDir: ${JSON.stringify(baseDir.replace(/\\/g, '/'))},
  projects: [
${projectsLiteral}
  ],
});
`;

  try {
    fs.writeFileSync(configPath, contents, 'utf-8');
  } catch (err) {
    // Never let an unwritable config directory kill the run — fall back to base config.
    console.warn('[ControlCenter] Could not write effective Playwright config, using project config as-is:', err);
    return null;
  }

  let cleaned = false;
  const cleanup = () => {
    if (cleaned) return;
    cleaned = true;
    try {
      fs.rmSync(configPath, { force: true });
    } catch {
      /* best effort — a leftover dotfile never blocks anything */
    }
  };
  return { configPath, cleanup };
}
